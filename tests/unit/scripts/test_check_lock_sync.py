def _mv_die_slaagt_maar_faalt(bin_dir: Path) -> None:
    """Zet een `mv` op PATH die hernoemt en dáárna een foutstatus geeft.

    Modelleert twee echte gevallen tegelijk: een `mv` die de rename voltooit maar
    non-zero retourneert, en een signaal dat toeslaat tussen de voltooide rename
    en het moment waarop het script vastlegt dat er gemuteerd is.
    """
    mv = bin_dir / "mv"
    mv.write_text('#!/usr/bin/env bash\n/bin/mv "$@"\nexit 1\n', encoding="utf-8")
    mv.chmod(0o755)


def test_mutatie_die_zich_als_mislukt_meldt_wordt_teruggedraaid(tmp_path):
    """Een mv die hernoemt en daarna faalt, laat de lock niet gewijzigd achter.

    De transactievlag stond ná de `schrijf`-aanroep, dus pas nadat `mv` was
    teruggekeerd. Voltooide die de rename maar meldde hij een fout — of sloeg
    er een signaal toe tussen de rename en de vlagtoekenning — dan was de lock
    vervangen terwijl de vlag op 0 bleef. De trap herstelde dan niets en gooide
    de backups weg: een gemuteerde repo zonder weg terug.

    De vlag hoort daarom vóór de `mv` te staan en niet erna: hij betekent "het
    doel kan vanaf hier gemuteerd zijn", en bij twijfel draait een transactie
    terug. De `cp` erboven raakt het doel niet, dus die houdt de vlag op 0 —
    daar blijft een gefaalde voorbereiding dus terecht zonder rollback.
    """
    root = _repo(tmp_path)
    bin_dir = tmp_path / "bin"
    _fake_uv(bin_dir, runtime_body=LOCK_BODY, dev_body=DEV_LOCK_BODY)
    _mv_die_slaagt_maar_faalt(bin_dir)
    oorspronkelijk = (root / "requirements.txt").read_text(encoding="utf-8")

    resultaat = _draai_write(root, bin_dir)

    assert resultaat.returncode == 3, f"{resultaat.stdout}{resultaat.stderr}"
    assert (root / "requirements.txt").read_text(encoding="utf-8") == oorspronkelijk, (
        "de lock is vervangen door een mv die zich als mislukt meldde, en niet "
        "teruggedraaid; de transactie miste de mutatie"
    )


def test_credentials_over_een_line_continuation_worden_geredigeerd(tmp_path):
    """Een URL mag zich niet aan de redactie onttrekken door zich te splitsen.

    Requirements-bestanden voegen een regel die op een backslash eindigt samen
    met de volgende. De redactie werkte per fysieke regel, dus een directive die
    zijn credential over twee regels verdeelde ontsnapte: bij de userinfo-vorm
    staan `://` en `@` niet meer op dezelfde regel, en bij de queryvorm werd
    alleen de backslash gemaskeerd terwijl de waarde eronder bleef staan.
    """
    root = _repo(tmp_path)
    (root / "requirements.txt").write_text(
        HEADER
        + "--index-url https://gebruiker:\\\nGEHEIM789@index.example/simple\n"
        + "--extra-index-url https://index.example/extra?token=\\\nGEHEIM012\n"
        + LOCK_BODY,
        encoding="utf-8",
    )
    _fake_uv(tmp_path / "bin", runtime_body=LOCK_BODY, dev_body=DEV_LOCK_BODY)

    resultaat = _draai(root, tmp_path / "bin")

    assert resultaat.returncode == 1, resultaat.stderr
    assert "GEHEIM789" not in resultaat.stderr, resultaat.stderr
    assert "GEHEIM012" not in resultaat.stderr, resultaat.stderr
    # De hostnamen blijven staan, anders is de melding niet te diagnosticeren.
    assert "index.example" in resultaat.stderr, resultaat.stderr


def test_ingesprongen_userinfo_continuation_wordt_geredigeerd(tmp_path):
    """Een vervolgregel mag zijn geheim niet achter inspringing verbergen.

    Het samenvoegen haalde de diff-prefix van de vervolgregel weg, maar liet de
    inspringing staan. De userinfo-regex eist niet-witruimte tussen `://` en de
    `@`, dus `gebruiker:    GEHEIM@host` matchte niet en het wachtwoord ging
    ongemaskeerd naar stderr — en daarmee naar het publieke joblog.

    Inspringing is hier geen kunstgreep: pip en uv accepteren een ingesprongen
    vervolgregel, en menig editor voegt haar vanzelf toe.
    """
    root = _repo(tmp_path)
    (root / "requirements.txt").write_text(
        HEADER
        + "--index-url https://gebruiker:\\\n    GEHEIM_INDENT@index.example/simple\n"
        + LOCK_BODY,
        encoding="utf-8",
    )
    _fake_uv(tmp_path / "bin", runtime_body=LOCK_BODY, dev_body=DEV_LOCK_BODY)

    resultaat = _draai(root, tmp_path / "bin")

    assert resultaat.returncode == 1, resultaat.stderr
    assert "GEHEIM_INDENT" not in resultaat.stderr, resultaat.stderr
    # Diagnose blijft nodig: host en directive horen zichtbaar te blijven.
    assert "index-url" in resultaat.stderr, resultaat.stderr
    assert "index.example" in resultaat.stderr, resultaat.stderr


