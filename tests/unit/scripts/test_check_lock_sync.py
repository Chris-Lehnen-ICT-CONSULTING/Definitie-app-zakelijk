"""Tests voor scripts/ci/check_lock_sync.sh (DEF-559/DEF-711).

Deze gate bewaakt of de gecommitte lock hoort bij de gecommitte .in-bron. Hij
stond eerder structureel rood — zelfs direct na `make lock` — en werd daarom
genegeerd, waarna een echte desync ongemerkt op main landde: `setuptools` viel
uit requirements.txt terwijl requirements.in het pinde. Zonder test bewaakt niets
dat de gate zijn discriminerende vermogen houdt.

`uv` wordt gestubd. Een echte resolve kost seconden en netwerk, en zou de test
afhankelijk maken van PyPI-beschikbaarheid; de stub maakt alle uitkomsten
deterministisch en toetst precies wat dit script zelf doet — het vergelijken van
de resolve-uitvoer met de gecommitte lock, en het onderscheiden van de
foutklassen.

Exit-codes van het script: 0 sync, 1 desync, 2 resolve-fout, 3 preconditie.
Die zijn alleen zichtbaar bij een directe aanroep; `make lock-check` vertaalt
elke fout naar make-exitcode 2.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import pytest

pytestmark = [pytest.mark.unit]

SCRIPT = (
    Path(__file__).parent.parent.parent.parent / "scripts" / "ci" / "check_lock_sync.sh"
)

# De eerste twee regels van een uv-lock zijn de header; het script strips die
# voor de vergelijking, omdat de check met --no-header compileert.
HEADER = "# This file was autogenerated by uv via the following command:\n#    uv pip compile\n"

# De bodies dragen hashes, net als de echte lockfiles. Zonder hashes in de
# fixture blijft een scriptmutatie die `--hash`-regels uit de vergelijking
# strip onzichtbaar, terwijl die een gemanipuleerde lock groen zou verklaren.
LOCK_BODY = (
    "voorbeeld==1.0.0 \\\n"
    "    --hash=sha256:1111111111111111111111111111111111111111111111111111111111111111\n"
    "    # via -r requirements.in\n"
)
DEV_LOCK_BODY = (
    "voorbeeld-dev==2.0.0 \\\n"
    "    --hash=sha256:2222222222222222222222222222222222222222222222222222222222222222\n"
    "    # via -r requirements-dev.in\n"
)

# De pin die in het compile-doel moet staan wil het als versievoorkeur gelden.
# De stub gebruikt dit om te bepalen of het script de lock daadwerkelijk heeft
# gekopieerd — niet of het bestand toevallig niet leeg is.
RUNTIME_PIN = "voorbeeld==1.0.0"
DEV_PIN = "voorbeeld-dev==2.0.0"

# Wat de stub in write-modus boven de body schrijft (geen --no-header), zodat
# een assertie op de volledige uitvoer één bron deelt met de stub zelf.
VERWACHTE_WRITE_HEADER = (
    "# This file was autogenerated by uv via the following command:\n"
    "#    make lock\n"
)


def _fake_uv(
    bin_dir: Path,
    *,
    runtime_body: str,
    dev_body: str,
    exit_code: int = 0,
    dev_exit_code: int = 0,
    body_zonder_voorkeur: str | None = None,
    dev_body_zonder_voorkeur: str | None = None,
    foutmelding: str = "error: kan niet resolven",
) -> None:
    """Zet een uv-stub op PATH die zich als een strenge uv gedraagt.

    De stub is bewust wantrouwig, want een toegeeflijke stub laat kapotte
    varianten van het script groen: hij schrijft dan nog steeds de verwachte
    body en de suite merkt niets. Daarom weigert deze stub onbekende vlaggen,
    controleert hij dat bron- en constraintpaden bestaan, en bepaalt hij de
    versievoorkeur op INHOUD.

    Dat laatste is het cruciale punt. uv gebruikt een bestaand `-o`-bestand als
    versievoorkeur. Een stub die alleen kijkt of dat bestand niet leeg is, is te
    zwak: vervang de kopieerstap door iets dat enkel de header schrijft en het
    doel is niet-leeg maar bevat geen enkele pin — echte uv zou dan vrij
    upgraden, terwijl zo een stub gewoon de goede body teruggeeft. Deze stub
    kijkt daarom of de verwachte pin daadwerkelijk in het doel staat.
    """
    bin_dir.mkdir(parents=True, exist_ok=True)
    uv = bin_dir / "uv"
    vrije_body = (
        body_zonder_voorkeur if body_zonder_voorkeur is not None else runtime_body
    )
    dev_vrije_body = (
        dev_body_zonder_voorkeur if dev_body_zonder_voorkeur is not None else dev_body
    )
    # De stub legt zijn volledige argv vast, zodat tests kunnen toetsen wélke
    # vlaggen het script meegeeft. Zonder die controle blijft het wegvallen van
    # -c of --no-header onzichtbaar: de gate gaat dan stuk terwijl alle tests
    # groen blijven.
    argv_log = bin_dir / "argv.log"
    uv.write_text(
        "#!/usr/bin/env bash\n"
        f'printf "%s\\n" "$*" >> {str(argv_log)!r}\n'
        'if [ "$1" != "pip" ] || [ "$2" != "compile" ]; then\n'
        '  echo "error: onverwacht subcommando $1 $2" >&2\n'
        "  exit 2\n"
        "fi\n"
        "shift 2\n"
        'bron=""\n'
        'doel=""\n'
        'constraint=""\n'
        # Echte uv schrijft altijd een header, tenzij --no-header meekomt. De
        # stub volgt dat, zodat een write-dan-check-round-trip de headerstrip
        # van `vergelijk()` werkelijk doorloopt in plaats van hem over te slaan.
        "geen_header=0\n"
        "while [ $# -gt 0 ]; do\n"
        '  case "$1" in\n'
        "    --universal|--generate-hashes) ;;\n"
        "    --no-header) geen_header=1 ;;\n"
        "    --custom-compile-command) shift ;;\n"
        "    -o) shift; doel=$1 ;;\n"
        "    -c) shift; constraint=$1 ;;\n"
        "    -*)\n"
        '      echo "error: onbekende vlag $1" >&2\n'
        "      exit 2\n"
        "      ;;\n"
        # Exact één positionele bron. Alleen de eerste onthouden liet een
        # tweede bron ongemerkt passeren, terwijl echte uv daarop een andere
        # resolutie geeft.
        "    *)\n"
        '      if [ -n "$bron" ]; then\n'
        '        echo "error: meer dan één bronbestand ($bron en $1)" >&2\n'
        "        exit 2\n"
        "      fi\n"
        "      bron=$1\n"
        "      ;;\n"
        "  esac\n"
        "  shift\n"
        "done\n"
        # De bronnaam moet exact kloppen. Alleen op bestaan controleren is te
        # zwak: dan valt elk pad dat niet op requirements-dev.in eindigt in de
        # runtime-tak, en blijft een script dat per ongeluk requirements.txt
        # compileert onopgemerkt.
        'basisnaam=$(basename "$bron")\n'
        'if [ "$basisnaam" != "requirements.in" ] && '
        '[ "$basisnaam" != "requirements-dev.in" ]; then\n'
        '  echo "error: onverwacht bronbestand $bron" >&2\n'
        "  exit 2\n"
        "fi\n"
        'if [ ! -f "$bron" ]; then\n'
        '  echo "error: bronbestand $bron bestaat niet" >&2\n'
        "  exit 2\n"
        "fi\n"
        # Aparte exitcode per tak, zodat een fout die alleen tijdens de
        # dev-resolve optreedt afzonderlijk te testen is.
        'if [ "$basisnaam" = "requirements-dev.in" ]; then\n'
        f"  if [ {dev_exit_code} -ne 0 ]; then\n"
        f"    echo {foutmelding!r} >&2\n"
        f"    exit {dev_exit_code}\n"
        "  fi\n"
        "else\n"
        f"  if [ {exit_code} -ne 0 ]; then\n"
        f"    echo {foutmelding!r} >&2\n"
        f"    exit {exit_code}\n"
        "  fi\n"
        "fi\n"
        'if [ -n "$constraint" ] && [ ! -f "$constraint" ]; then\n'
        '  echo "error: constraint $constraint bestaat niet" >&2\n'
        "  exit 2\n"
        "fi\n"
        'if [ -z "$doel" ]; then\n'
        '  echo "error: geen -o meegegeven" >&2\n'
        "  exit 2\n"
        "fi\n"
        # Het voorkeurbestand mag geen hashes bevatten. Echte uv neemt die
        # namelijk over in plaats van ze te herberekenen, waardoor een lock met
        # gemanipuleerde hashes zijn eigen corruptie erft en de gate groen
        # meldt. Zonder deze controle houdt precies die oude implementatie —
        # de volledige lock naar het doel kopiëren — de suite groen.
        'if [ -f "$doel" ] && grep -q -- "--hash=" "$doel"; then\n'
        '  echo "error: voorkeurbestand bevat hashes; uv zou ze overnemen" >&2\n'
        "  exit 2\n"
        "fi\n"
        # Schrijft de uitvoer, voorafgegaan door een header tenzij --no-header
        # meekwam. %b, niet %s: de body komt als Python-repr binnen, dus met
        # \n-escapes die de shell nog moet interpreteren.
        "schrijf_uitvoer() {\n"
        '  : > "$doel"\n'
        '  if [ "$geen_header" = 0 ]; then\n'
        "    printf '%b' '# This file was autogenerated by uv via the following"
        ' command:\\n#    make lock\\n\' >> "$doel"\n'
        "  fi\n"
        '  printf \'%b\' "$1" >> "$doel"\n'
        "}\n"
        'case "$bron" in\n'
        "  *requirements-dev.in)\n"
        f'    if grep -qF {DEV_PIN!r} "$doel" 2>/dev/null; then\n'
        f"      schrijf_uitvoer {dev_body!r}\n"
        "    else\n"
        f"      schrijf_uitvoer {dev_vrije_body!r}\n"
        "    fi\n"
        "    ;;\n"
        "  *)\n"
        f'    if grep -qF {RUNTIME_PIN!r} "$doel" 2>/dev/null; then\n'
        f"      schrijf_uitvoer {runtime_body!r}\n"
        "    else\n"
        f"      schrijf_uitvoer {vrije_body!r}\n"
        "    fi\n"
        "    ;;\n"
        "esac\n",
        encoding="utf-8",
    )
    uv.chmod(0o755)


def _repo(tmp_path: Path) -> Path:
    """Bouw een minimale repo-structuur met .in-bronnen en locks."""
    root = tmp_path / "repo"
    root.mkdir()
    (root / "requirements.in").write_text("voorbeeld==1.0.0\n", encoding="utf-8")
    (root / "requirements-dev.in").write_text(
        "voorbeeld-dev==2.0.0\n", encoding="utf-8"
    )
    (root / "requirements.txt").write_text(HEADER + LOCK_BODY, encoding="utf-8")
    (root / "requirements-dev.txt").write_text(HEADER + DEV_LOCK_BODY, encoding="utf-8")
    return root


def _draai(root: Path, bin_dir: Path | None) -> subprocess.CompletedProcess[str]:
    env = dict(os.environ)
    env["LOCK_SYNC_ROOT"] = str(root)
    # Beperk PATH tot de stub plus de systeempaden die bash/diff/sed leveren,
    # zodat een echte uv uit de dev-omgeving de test niet stilletjes overneemt.
    basis = "/usr/bin:/bin:/usr/sbin:/sbin"
    env["PATH"] = f"{bin_dir}:{basis}" if bin_dir else basis
    return subprocess.run(
        ["bash", str(SCRIPT)],
        capture_output=True,
        text=True,
        env=env,
        check=False,
    )


def _draai_write(
    root: Path, bin_dir: Path, *extra: str, tmpdir: Path | None = None
) -> subprocess.CompletedProcess[str]:
    """Zoals `_draai`, maar met --write en optionele extra argumenten."""
    env = dict(os.environ)
    env["LOCK_SYNC_ROOT"] = str(root)
    env["PATH"] = f"{bin_dir}:/usr/bin:/bin:/usr/sbin:/sbin"
    if tmpdir is not None:
        env["TMPDIR"] = str(tmpdir)
    return subprocess.run(
        ["bash", str(SCRIPT), "--write", *extra],
        capture_output=True,
        text=True,
        env=env,
        check=False,
    )


def test_lock_in_sync_geeft_exit_0(tmp_path):
    """De gate slaagt wanneer de resolve gelijk is aan de gecommitte lock."""
    root = _repo(tmp_path)
    _fake_uv(tmp_path / "bin", runtime_body=LOCK_BODY, dev_body=DEV_LOCK_BODY)

    resultaat = _draai(root, tmp_path / "bin")

    assert resultaat.returncode == 0, resultaat.stderr
    assert "OK:" in resultaat.stdout


def test_lock_wordt_als_versievoorkeur_meegegeven(tmp_path):
    """De kern van DEF-559: de check moet dezelfde voorkeur krijgen als `make lock`.

    uv gebruikt een bestaand -o-bestand als versievoorkeur. Kopieert het script
    de lock niet naar het compile-doel, dan resolvet uv vrij en kiest hij de
    nieuwste versies — waarna de gate rood staat op niets meer dan een upstream
    release. Precies zo faalde deze gate structureel, zelfs direct na `make lock`.

    De stub schrijft een afwijkende body zodra het doel leeg is, dus deze test
    wordt rood als de kopieerstap uit het script verdwijnt.
    """
    root = _repo(tmp_path)
    _fake_uv(
        tmp_path / "bin",
        runtime_body=LOCK_BODY,
        dev_body=DEV_LOCK_BODY,
        body_zonder_voorkeur="voorbeeld==1.1.0\n    # via -r requirements.in\n",
    )

    resultaat = _draai(root, tmp_path / "bin")

    assert resultaat.returncode == 0, (
        "De gate hoort groen te zijn: de lock is geldig. Rood betekent dat de "
        f"versievoorkeur niet is meegegeven.\n{resultaat.stderr}"
    )


